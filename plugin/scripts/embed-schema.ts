/**
 * @file Embed `schema/chart.sql` into `plugin/src/schema.ts`.
 *
 * The plugin must work when copied away from this repository, so it carries
 * the chart DDL as a module instead of reading the shared file at run time.
 * `schema/chart.sql` stays the single source of truth: run this script after
 * changing it (the plugin tests fail while the copy is stale).
 *
 * Usage: `bun scripts/embed-schema.ts [--check]`; `--check` only reports
 * whether `src/schema.ts` is current and exits 1 when it is not.
 */

import { readFileSync, writeFileSync } from "node:fs";

/** Shared chart DDL. */
const SOURCE = new URL("../../schema/chart.sql", import.meta.url);

/** Generated module. */
const TARGET = new URL("../src/schema.ts", import.meta.url);

/**
 * Render the module embedding a schema.
 *
 * @param sql Chart DDL.
 * @returns TypeScript source.
 */
export function renderSchemaModule(sql: string): string {
  const literal = sql.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
  return `/**
 * @file Chart DDL embedded from \`schema/chart.sql\`, so the plugin works outside this repository.
 *
 * Generated by \`scripts/embed-schema.ts\`; do not edit. Regenerate after
 * changing \`schema/chart.sql\`.
 */

/** Contents of \`schema/chart.sql\`. */
export const CHART_SCHEMA = \`${literal}\`;
`;
}

if (import.meta.main) {
  const expected = renderSchemaModule(readFileSync(SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    const current = readFileSync(TARGET, "utf8");
    if (current !== expected) {
      console.error("src/schema.ts is stale; run `bun scripts/embed-schema.ts`");
      process.exit(1);
    }
    console.log("src/schema.ts is current");
  } else {
    writeFileSync(TARGET, expected);
    console.log("wrote src/schema.ts");
  }
}
